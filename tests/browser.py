"""Run with a server on port 3000 and Python Playwright + Chromium installed."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
BASE = Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1440,'height':1100}, accept_downloads=True)
    page = context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto('http://127.0.0.1:3000/',wait_until='networkidle')
    expect(page.locator('.format-card')).to_have_count(7)
    page.locator('[data-filter="native"]').click()
    expect(page.locator('.format-card')).to_have_count(1)
    page.locator('[data-filter="all"]').click()
    page.locator('#search').fill('billboard')
    expect(page.locator('.format-card')).to_have_count(1)
    page.locator('#search').fill('')
    for name in ['leaderboard','rectangle','billboard','native','carousel','mobile']:
        page.locator(f'[data-open="{name}"]').first.click()
        preview=page.frame_locator('#ad-preview')
        expect(preview.locator('.headline')).to_have_text('Your next chapter starts here.')
        if name=='carousel':
            page.locator('#slide-2-headline').fill('Custom second slide')
            expect(page.locator('#ad-preview')).to_have_css('pointer-events','auto')
            preview.get_by_role('button',name='Slide 2').click()
            expect(preview.locator('.headline')).to_have_text('Custom second slide')
        page.get_by_role('button',name='Close editor').click()
    page.locator('#new-creative').click()
    page.locator('#creative-name').fill('Test campaign')
    page.locator('#headline').fill('A new Irish adventure')
    expect(page.frame_locator('#ad-preview').locator('.headline')).to_have_text('A new Irish adventure')
    page.locator('#destination').fill('javascript:alert(1)')
    page.locator('#save').click()
    expect(page.locator('#toast')).to_contain_text('complete http://')
    page.locator('#destination').fill('https://example.com/campaign')
    page.locator('#image').set_input_files({'name':'campaign.png','mimeType':'image/png','buffer':__import__('base64').b64decode('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=')})
    expect(page.frame_locator('#ad-preview').locator('.photo')).to_have_attribute('src',__import__('re').compile('data:image/png;base64,'))
    page.locator('#save').click()
    expect(page.locator('#draft-count')).to_have_text('1')
    page.locator('[data-preview="site"]').click()
    expect(page.locator('#site-context')).to_be_visible()
    with page.expect_download() as dl: page.locator('#export').click()
    export_path=BASE/'dist'/'test-campaign.html'
    dl.value.save_as(export_path)
    exported=page.context.new_page()
    exported.route('**/export-test',lambda route:route.fulfill(body=export_path.read_text(),content_type='text/html'))
    exported.goto('http://127.0.0.1:3000/export-test')
    expect(exported.locator('.headline')).to_have_text('A new Irish adventure')
    expect(exported.locator('.cta')).to_have_attribute('href','https://example.com/campaign')
    exported.close()
    page.get_by_role('button',name='Close editor').click()
    page.locator('[data-view="drafts"]').click()
    expect(page.locator('.format-card')).to_have_count(1)
    page.reload()
    page.locator('[data-view="drafts"]').click()
    expect(page.locator('.format-card h3')).to_have_text('Test campaign')
    page.locator('.card-action').click()
    expect(page.locator('#headline')).to_have_value('A new Irish adventure')
    page.get_by_role('button',name='Close editor').click()
    page.once('dialog',lambda dialog:dialog.accept())
    page.locator('[data-delete]').click()
    expect(page.locator('.format-card')).to_have_count(0)
    page.locator('[data-view="formats"]').click()
    page.screenshot(path=str(BASE/'dist'/'ad-studio-desktop.png'),full_page=True)
    page.locator('#new-creative').click()
    page.screenshot(path=str(BASE/'dist'/'ad-studio-editor.png'),full_page=True)
    page.get_by_role('button',name='Close editor').click()
    page.set_viewport_size({'width':390,'height':844})
    expect(page.locator('.format-card')).to_have_count(7)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile overflow'
    page.screenshot(path=str(BASE/'dist'/'ad-studio-mobile.png'),full_page=True)
    page.locator('#new-creative').click()
    expect(page.locator('#editor')).to_be_visible()
    assert page.locator('#editor').evaluate('(e)=>e.scrollWidth<=e.clientWidth'), 'Editor overflow'
    standalone=page.context.new_page()
    standalone.on('pageerror',lambda e:print('STANDALONE ERROR:',e,flush=True))
    standalone.route('**/standalone-test',lambda route:route.fulfill(body=(BASE/'dist'/'ad-studio.html').read_text(),content_type='text/html'))
    standalone.goto('http://127.0.0.1:3000/standalone-test')
    expect(standalone.locator('.format-card')).to_have_count(7)
    standalone.locator('[data-open="carousel"]').first.click()
    standalone.locator('#slide-2-headline').fill('Standalone slide')
    standalone.locator('#ad-preview').element_handle().content_frame().wait_for_function("() => document.querySelector('script')?.textContent.includes('Standalone slide')")
    standalone.frame_locator('#ad-preview').get_by_role('button',name='Slide 2').press('Enter')
    expect(standalone.frame_locator('#ad-preview').locator('.headline')).to_have_text('Standalone slide')
    assert not errors, errors
    browser.close()
    print('PASS: seven formats, filters, search, live edits, carousel, URL validation, image upload, save/reload/edit/delete, HTML export, context preview, mobile layout, standalone app; no JS errors.')
